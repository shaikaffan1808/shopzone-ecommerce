@Injectable({ providedIn: 'root' })
export class LocaleService {
  private readonly storageKey = 'ecommerce_locale';
  private readonly localeSignal = signal<SupportedLocale>(this.loadLocale());
  readonly locale = this.localeSignal.asReadonly();

  constructor() {
    this.updateDocumentLanguage(this.localeSignal());
  }

  private loadLocale(): SupportedLocale {
    const savedLocale = localStorage.getItem(this.storageKey);
    return savedLocale && Object.hasOwn(translations, savedLocale)
      ? savedLocale as SupportedLocale
      : 'en-IN';
  }

  setLocale(locale: SupportedLocale): void {
    if (!Object.hasOwn(translations, locale)) {
      throw new RangeError(`Unsupported locale: ${locale}`);
    }
    localStorage.setItem(this.storageKey, locale);
    this.localeSignal.set(locale);
    this.updateDocumentLanguage(locale);
  }

  translate(key: string, params: Record<string, string | number> = {}): string {
    const value = translations[this.localeSignal()]?.[key] ?? translations['en-IN']?.[key] ?? key;
    return Object.entries(params).reduce(
      (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
      value
    );
  }

  formatNumber(value: number, options?: Intl.NumberFormatOptions): string {
    return new Intl.NumberFormat(this.localeSignal(), options).format(value);
  }

  formatCurrency(value: number): string {
    return new Intl.NumberFormat(this.localeSignal(), {
      style: 'currency',
      currency: 'INR',
      maximumFractionDigits: 0
    }).format(value);
  }

  formatDate(value: Date | string | number): string {
    return new Intl.DateTimeFormat(this.localeSignal(), {
      dateStyle: 'medium'
    }).format(new Date(value));
  }

  private updateDocumentLanguage(locale: SupportedLocale): void {
    document.documentElement.lang = locale.split('-')[0];
  }
}
